/**
 * pull-ds-tokens — Figma → Storybook token feed, no manual export.
 *
 * Reuses the figma-code-converter's Desktop-Bridge peer (the plugin pushes the
 * COMPLETE variables catalog to any server in its scan range) and ds-export
 * (synthesizes the canonical export JSON shape). Run with Figma desktop open and
 * the Desktop Bridge plugin running:
 *
 *   node storybook/design-system/tokens/pull-ds-tokens.mjs
 *
 * Writes ds-tokens.generated.json next to this script:
 *   { pulledAtFileVersion, fileKey, export: <canonical export array> }
 * The Storybook token docs derive names/bindings/values/descriptions from it —
 * the same variables the design file holds, one command fresh.
 */
import path from 'node:path';
import { promises as fs } from 'node:fs';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const TOOL = path.resolve(HERE, '../../../figma-code-converter');

const { startBridgePeer } = await import(path.join(TOOL, 'src/bridge-peer.mjs'));
const { toDsExport } = await import(path.join(TOOL, 'src/ds-export.mjs'));

const WAIT_MS = 600_000;

console.log('[pull-ds-tokens] starting bridge peer (plugin scan range 9223-9232)…');
const bridge = await startBridgePeer({ log: (m) => console.log(`[bridge] ${m}`) });
console.log(`[pull-ds-tokens] listening on ${bridge.port} — waiting for the Desktop Bridge plugin to push the catalog…`);

const started = Date.now();
while (!bridge.state.connected) {
  if (Date.now() - started > WAIT_MS) {
    console.error(
      '[pull-ds-tokens] no catalog push within 90s. Is Figma desktop open with the Desktop Bridge plugin running?\n' +
      '  Figma → Plugins → Development → Desktop Bridge (the plugin rescans ports periodically; reopen it to force).',
    );
    bridge.close();
    process.exit(1);
  }
  await new Promise((r) => setTimeout(r, 500));
}

console.log('[pull-ds-tokens] plugin connected — requesting fresh catalog (REFRESH_VARIABLES)…');
const data = await bridge.freshVariables(30_000);
if (!data) { console.error('[pull-ds-tokens] connected but no catalog delivered'); bridge.close(); process.exit(1); }
const fileVersion = bridge.state.fileInfo?.version ?? null;
const out = {
  fileKey: data.fileKey ?? null,
  pulledAtFileVersion: fileVersion,
  variables: data.variables?.length ?? 0,
  export: toDsExport(data),
};
const target = path.join(HERE, 'ds-tokens.generated.json');
await fs.writeFile(target, JSON.stringify(out, null, 1));
console.log(`[pull-ds-tokens] wrote ${target} — ${out.variables} variables @ file version ${fileVersion}`);

// ── compact resolved view of the semantic colour tier (what the docs render) ──
// Walk the export, resolve alias {dot.path} chains per theme face. Primitive
// collections carry Light/Dark modes (face = mode index); single-mode tiers pass through.
const byColl = new Map(out.export.map((c) => { const n = Object.keys(c)[0]; return [n, c[n].modes]; }));
const leafAt = (tree, dotPath) => dotPath.split('.').reduce((t, k) => (t ? t[k] : undefined), tree);
const resolveFace = (leaf, face, depth = 0) => {
  if (!leaf || depth > 8) return null;
  const v = leaf.$value;
  if (typeof v === 'string' && v.startsWith('{')) {
    const modes = byColl.get(leaf.$collectionName);
    if (!modes) return null;
    const names = Object.keys(modes);
    const tree = modes[names.length > 1 ? names[face === 'L' ? 0 : 1] : names[0]];
    return resolveFace(leafAt(tree, v.slice(1, -1)), face, depth + 1);
  }
  return v;
};
const semName = [...byColl.keys()].find((n) => n.includes('Sem-Col'));
const semTree = byColl.get(semName)[Object.keys(byColl.get(semName))[0]];
const rows = [];
const walk = (t, prefix) => {
  for (const [k, v] of Object.entries(t)) {
    if (!v || typeof v !== 'object') continue;
    // a node can be BOTH a token and a group (bare family token + its variants folder)
    if ('$type' in v) {
      const binding = typeof v.$value === 'string' && v.$value.startsWith('{')
        ? v.$value.slice(1, -1).replaceAll('.', '/') : 'RAW';
      rows.push({ name: prefix + k, binding, description: v.$description ?? '',
        L: resolveFace(v, 'L'), D: resolveFace(v, 'D') });
    }
    const kids = Object.fromEntries(Object.entries(v).filter(([kk]) => !kk.startsWith('$')));
    if (Object.keys(kids).length) walk(kids, prefix + k + '/');
  }
};
walk(semTree, '');
const resolved = { fileKey: out.fileKey, pulledAtFileVersion: fileVersion, tokens: rows };
const target2 = path.join(HERE, 'sem-col.resolved.json');
await fs.writeFile(target2, JSON.stringify(resolved, null, 1));
console.log(`[pull-ds-tokens] wrote ${target2} — ${rows.length} semantic colour tokens, both faces resolved`);
const target3 = path.join(HERE, 'sem-col.resolved.ts');
await fs.writeFile(target3, `// GENERATED by pull-ds-tokens.mjs — do not edit. Source: the Figma file.\nexport const RESOLVED = ${JSON.stringify(resolved, null, 1)} as const;\n`);
console.log(`[pull-ds-tokens] wrote ${target3}`);
bridge.close();
process.exit(0);
