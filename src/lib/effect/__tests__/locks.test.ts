// locks.test.ts — THE SEALED PROFILE. Dan, 2026-09-04: "add locks to all configs and make them go
// through into the spec as locked as well so any prod cannot change them by accident unless we change
// it in the admin engine version." Three claims, each proved here rather than asserted:
//   1. a locked config overrides what a caller passes — at BOTH engine doors, not just the bench;
//   2. the answer carries the profile it was made under, so a record proves what was fixed;
//   3. the admin route refuses a seal the engine would not accept.

import { describe, expect, it, vi } from 'vitest'

/** The profile under test — mocked at the module the two doors read, which is exactly how a real
 *  profile reaches them (the file is generated by the Grid Lab). Locked: a coarser pitch and a wider
 *  padding than any caller below asks for, so a pass-through would be visible. */
const SEALED = {
  version: 1 as const,
  locks: {
    paddingMM: { value: 20, locked: true },
    pitchMM: { value: 96, locked: true },
    coverage: { value: 'full' as const, locked: true },
    governor: { value: 3, locked: false },      // remembered, NOT sealed
  },
}
vi.mock('../lock-profile', () => ({ LOCK_PROFILE: SEALED }))

const { LOCK_PROFILE, coverageLock, isLocked, sealRequest, sealed, sealedPlanValues, withLock } = await import('../locks')
const { solveGrid } = await import('../pipeline/solve')
const { resolveGridPlan } = await import('../grid-core')
const { normBaseContour } = await import('../grid-magnet-bridge')
const { getShape } = await import('@/lib/shape-library')
const { BANDS, CENTRE_MODE, GOVERNOR, PROTECTION_PADDING_MM, RELEASED_PADDING_MM } = await import('../grid-magnet-spec')

const base = normBaseContour(getShape('circle', 1024, 1024, {}), 1024)!

describe('the sealed profile', () => {
  it('every config the bench dials is lockable — one with no lock is one production can still change', async () => {
    const { LOCK_KEYS } = await import('../locks')
    // the dials Grid Lab offers, by the key each writes; a new dial without a lock fails here
    expect([...LOCK_KEYS].sort()).toEqual([
      'activeBandIds', 'centreMode', 'classifierRuler', 'coverage', 'governor',
      'paddingMM', 'pitchMM', 'plan', 'protectionPaddingMM',
    ])
  })

  it('a locked config wins over the caller; an unlocked one does not', () => {
    // a seal applies whether or not the caller mentioned the config — that is what sealing means
    expect(sealed({ paddingMM: 12, governor: 0 }))
      .toEqual({ paddingMM: 20, governor: 0, pitchMM: 96, coverage: 'full' })
    expect(isLocked(LOCK_PROFILE, 'paddingMM')).toBe(true)
    expect(isLocked(LOCK_PROFILE, 'governor'), 'remembered but released').toBe(false)
    expect(isLocked(LOCK_PROFILE, 'plan'), 'never touched').toBe(false)
    // and locking is a pure step on the profile — the admin's press, as data
    const next = withLock(LOCK_PROFILE, 'plan', 'all8', true)
    expect(next.locks.plan).toEqual({ value: 'all8', locked: true })
    expect(isLocked(withLock(next, 'plan', 'all8', false), 'plan')).toBe(false)
    expect(isLocked(LOCK_PROFILE, 'plan'), 'the original is untouched').toBe(false)
  })

  it('THE ADMIN DOOR: a request asking for the unlocked values is answered at the sealed ones', () => {
    const asked = {
      base, offsetMM: 0, mode: 4, manualBand: false, sizeMM: 0, stepSel: null,
      cfg: { pitchMM: 48, paddingMM: RELEASED_PADDING_MM, centreMode: CENTRE_MODE, governor: GOVERNOR, plan: 'all6' as const, perimeterOnly: true, circle: true },
      settings: { protectionPaddingMM: PROTECTION_PADDING_MM },
      activeBandIds: BANDS.map((b) => b.id),
    }
    const sealedReq = sealRequest(asked)
    expect(sealedReq.cfg.pitchMM, 'pitch sealed at 96').toBe(96)
    expect(sealedReq.cfg.paddingMM, 'padding sealed at 20').toBe(20)
    expect(sealedReq.cfg.perimeterOnly, 'coverage sealed to full grid').toBe(false)
    expect(sealedReq.cfg.governor, 'released, so the caller keeps it').toBe(GOVERNOR)
    expect(asked.cfg.pitchMM, 'the caller\'s own request is not mutated').toBe(48)

    const solve = solveGrid(asked)
    expect(solve.grid.pitchCentreMM, 'the engine solved on the sealed lattice').toBe(96)
    expect(solve.grid.spotRadiusMM, 'and the sealed padding').toBe(20)
    // 3 — the record proves what was fixed when it was made
    expect(solve.profile).toEqual(SEALED)
  }, 180_000)

  it('THE RECORD DOOR: a delivered record wears the sealed coverage, not the caller\'s', async () => {
    const { deliverRecord } = await import('../pipeline')
    const { catalogue } = await import('../library')
    const circle = catalogue(48).find((e) => e.classId === 'circle' && e.frameCols === 3 && e.frameRows === 3 && e.nodesMM.length === 9)!
    const delivered = deliverRecord({ record: circle, cfg: { plan: 'all6', perimeterOnly: true }, settings: { protectionPaddingMM: PROTECTION_PADDING_MM } })
    expect(delivered.grid.anchors, 'coverage sealed to full: the belt the caller asked for is refused').toHaveLength(9)
    expect(delivered.grid.pitchCentreMM, 'a record\'s lattice is its own, not the sealed pitch dial').toBe(48)
    expect(delivered.profile).toEqual(SEALED)
  })

  it('THE PRODUCTION DOOR: resolveGridPlan cannot be talked out of a sealed value', () => {
    expect(sealedPlanValues()).toEqual({ paddingMM: 20, pitchMM: 96 })
    expect(coverageLock()).toBe('full')
    const contour = { outer: { pts: base.outer.pts.map(([x, y]) => [x * 200, y * 200] as [number, number]) }, holes: [] }
    const plan = resolveGridPlan(contour, { paddingMM: RELEASED_PADDING_MM, pitchMM: 48 })
    expect(plan.pitchMM, 'production asked for the 48 lattice and got the sealed 96').toBe(96)
    expect(plan.grid.pitchCentreMM).toBe(96)
    // the control: with no seal there is nothing to lay over the caller, so the assertion above is
    // the LOCK doing the work rather than the door ignoring the option it was given
    expect(sealedPlanValues({ version: 1, locks: {} })).toEqual({})
    expect(coverageLock({ version: 1, locks: {} })).toBeUndefined()
  }, 120_000)
})

describe('the admin route refuses a seal the engine would not accept', async () => {
  const { unsound } = await import('@/app/api/dev/lock-profile/validate')
  it('checks every locked value against what the engine takes', () => {
    expect(unsound({ version: 1, locks: {} })).toBeNull()
    expect(unsound({ version: 1, locks: { pitchMM: { value: 48, locked: true } } })).toBeNull()
    expect(unsound({ version: 1, locks: { pitchMM: { value: 60, locked: true } } })).toMatch(/not a value/)
    expect(unsound({ version: 1, locks: { paddingMM: { value: 999, locked: true } } })).toMatch(/not a value/)
    expect(unsound({ version: 1, locks: { coverage: { value: 'some', locked: true } } })).toMatch(/not a value/)
    expect(unsound({ version: 1, locks: { plan: { value: 'auto', locked: true } } })).toMatch(/not a value/)
    expect(unsound({ version: 1, locks: { activeBandIds: { value: [1, 1], locked: true } } })).toMatch(/not a value/)
    expect(unsound({ version: 1, locks: { activeBandIds: { value: [1, 4], locked: true } } })).toBeNull()
    expect(unsound({ version: 1, locks: { classifierRuler: { value: 'legal', locked: true } } })).toBeNull()
    expect(unsound({ version: 1, locks: { classifierRuler: { value: 'inner', locked: true } } })).toMatch(/not a value/)
    expect(unsound({ version: 1, locks: { nope: { value: 1, locked: true } } })).toMatch(/unknown config/)
    expect(unsound({ version: 1, locks: { plan: { value: 'all8' } } })).toMatch(/locked must be/)
    expect(unsound({ version: 2, locks: {} })).toMatch(/version/)
  })
})
